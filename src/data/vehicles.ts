function docsFor(v: Pick<Vehicle, "condition" | "auctionGrade" | "mileageKm">): VehicleDocument[] {
  if (v.condition === "reconditioned") {
    return [
      {
        type: "auction-sheet",
        label: "Japanese auction sheet",
        note: `Grade ${v.auctionGrade ?? "4"} · mileage confirmed at ${v.mileageKm.toLocaleString("en-LK")} km · translated to English`,
      },
      { type: "inspection", label: "Drivora 150-point inspection", note: "Passed · underbody, paint depth, hybrid battery health checked" },
      { type: "cr", label: "Customs clearance papers", note: "Duty paid · ready for first registration" },
    ];
  }
  if (v.condition === "used") {
    return [
      { type: "cr", label: "Certificate of registration", note: "Owner details masked · no finance outstanding" },
      { type: "service", label: "Service history", note: "Stamped book and agent invoices, mileage consistent" },
      { type: "inspection", label: "Drivora 150-point inspection", note: "Passed · report available on request" },
    ];
  }
  return [
    { type: "inspection", label: "Pre-delivery inspection", note: "Completed by the authorised agent" },
    { type: "service", label: "Agent warranty booklet", note: "Warranty starts on registration" },
  ];
}

